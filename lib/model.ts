// Token Radar, model radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol on the snapshot's watchlist, plus every protocol below the
// watchlist floor that passes the watchlist's own test. A protocol is rankable when its index
// entry records no token (no market cap, no CoinGecko id, no symbol) and it is not a wrapped,
// staked or bridged product of one that trades, not an exchange, and not a versioned pool of
// another protocol. The house's starter applies that test to the watchlist only and takes its
// early rows by TVL alone; on this snapshot that lets 39 bridges, liquid-staking products and
// wrapped or staked products into the early radar. This model applies the same test to every
// row, so no ranked protocol is a product of a token that already trades.
//
// Above the floor the watchlist's own line is respected: twenty protocols at or above $50M
// that the watchlist leaves out are not ranked. The watchlist was built from DefiLlama records
// that carry a parent protocol, which this snapshot does not, so the house's exclusion of them
// is followed rather than second-guessed from the snapshot's ten fields alone.
//
// Implied value follows only from the snapshot's own figures:
//
//   base         = tvl_usd x BASE_MULTIPLE
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth      = 1 + 0.04 x min(max(chains - 1, 0), 5)
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// TVL is the launch's scale, seven-day growth is its momentum, age with no token is how long
// the launch has been waited for, and the number of chains it runs on is how wide its user
// base reaches. No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
